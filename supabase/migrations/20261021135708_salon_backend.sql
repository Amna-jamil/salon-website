-- Application-owned authentication is retained. Only the Node backend connects
-- to this private schema; no browser API role can read customer or auth data.
CREATE SCHEMA salon;
REVOKE ALL ON SCHEMA salon FROM PUBLIC, anon, authenticated;
CREATE ROLE salon_backend LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOBYPASSRLS;
GRANT USAGE ON SCHEMA salon TO salon_backend;

CREATE TABLE salon.users(id TEXT PRIMARY KEY, email TEXT UNIQUE NOT NULL, password_hash TEXT NOT NULL, role TEXT NOT NULL CHECK(role IN ('admin','customer')), created_at TEXT NOT NULL);
CREATE TABLE salon.superadmins(user_id TEXT PRIMARY KEY REFERENCES salon.users(id) ON DELETE CASCADE);
CREATE TABLE salon.sessions(token_hash TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES salon.users(id) ON DELETE CASCADE, csrf TEXT NOT NULL, expires_at BIGINT NOT NULL);
CREATE TABLE salon.guest_sessions(token_hash TEXT PRIMARY KEY, expires_at BIGINT NOT NULL);
CREATE TABLE salon.settings(id INTEGER PRIMARY KEY CHECK(id=1), data TEXT NOT NULL CHECK(jsonb_typeof(data::jsonb)='object'), revision INTEGER NOT NULL DEFAULT 1);
CREATE TABLE salon.request_state(id INTEGER PRIMARY KEY CHECK(id=1), revision INTEGER NOT NULL DEFAULT 1);
CREATE TABLE salon.appointments(id TEXT PRIMARY KEY, data TEXT NOT NULL CHECK(jsonb_typeof(data::jsonb)='object'), created_order BIGINT GENERATED ALWAYS AS IDENTITY);
CREATE TABLE salon.conversations(id TEXT PRIMARY KEY, guest_hash TEXT NOT NULL REFERENCES salon.guest_sessions(token_hash), name TEXT NOT NULL, phone TEXT NOT NULL, created_at TEXT NOT NULL, updated_at TEXT NOT NULL, admin_read_at TEXT NOT NULL DEFAULT '');
CREATE TABLE salon.messages(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, conversation_id TEXT NOT NULL REFERENCES salon.conversations(id) ON DELETE CASCADE, sender TEXT NOT NULL CHECK(sender IN ('customer','admin')), body TEXT NOT NULL, created_at TEXT NOT NULL);

CREATE INDEX messages_conversation ON salon.messages(conversation_id,id);
CREATE INDEX conversations_guest ON salon.conversations(guest_hash);
CREATE INDEX conversations_updated ON salon.conversations(updated_at DESC);
CREATE INDEX sessions_expiry ON salon.sessions(expires_at);
CREATE INDEX sessions_user ON salon.sessions(user_id);

DO $security$
DECLARE table_name TEXT;
BEGIN
  FOREACH table_name IN ARRAY ARRAY['users','superadmins','sessions','guest_sessions','settings','request_state','appointments','conversations','messages'] LOOP
    EXECUTE format('ALTER TABLE salon.%I ENABLE ROW LEVEL SECURITY', table_name);
    EXECUTE format('ALTER TABLE salon.%I FORCE ROW LEVEL SECURITY', table_name);
    EXECUTE format('REVOKE ALL ON salon.%I FROM PUBLIC, anon, authenticated', table_name);
    EXECUTE format('GRANT SELECT,INSERT,UPDATE,DELETE ON salon.%I TO salon_backend', table_name);
    EXECUTE format('CREATE POLICY backend_only ON salon.%I FOR ALL TO salon_backend USING (true) WITH CHECK (true)', table_name);
  END LOOP;
END
$security$;
GRANT USAGE,SELECT ON ALL SEQUENCES IN SCHEMA salon TO salon_backend;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA salon FROM PUBLIC, anon, authenticated;
ALTER DEFAULT PRIVILEGES IN SCHEMA salon REVOKE ALL ON TABLES FROM PUBLIC, anon, authenticated;
ALTER DEFAULT PRIVILEGES IN SCHEMA salon REVOKE ALL ON SEQUENCES FROM PUBLIC, anon, authenticated;
